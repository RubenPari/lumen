const dicts: Record<string, Record<string, string>> = { it };

let lang = (typeof navigator !== "undefined" ? navigator.language : "en").slice(0, 2);
try {
  const saved = localStorage.getItem("lumen.lang");
  if (saved) lang = saved;
} catch {
  /* ignore */
}

export const currentLang = () => lang;

export function setLang(l: string) {
  lang = l;
  try {
    localStorage.setItem("lumen.lang", l);
  } catch {
    /* ignore */
  }
  location.reload();
}

export function t(key: string, ...args: (string | number)[]): string {
  let s = dicts[lang]?.[key] ?? key;
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, String(a));
  });
  return s;
}

export const locale = () => (lang === "it" ? "it-IT" : undefined);
